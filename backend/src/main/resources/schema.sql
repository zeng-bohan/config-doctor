CREATE TABLE IF NOT EXISTS lab_cases (
    id VARCHAR(100) PRIMARY KEY,
    symptom VARCHAR(2000) NOT NULL,
    config_json CLOB NOT NULL,
    config_version BIGINT NOT NULL,
    created_at_ms BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS lab_tasks (
    id VARCHAR(36) PRIMARY KEY,
    case_id VARCHAR(100) NOT NULL,
    symptom VARCHAR(2000) NOT NULL,
    status VARCHAR(20) NOT NULL,
    version BIGINT NOT NULL,
    idempotency_key VARCHAR(200) NOT NULL UNIQUE,
    request_hash VARCHAR(64) NOT NULL,
    run_token VARCHAR(36),
    lease_until_ms BIGINT,
    messages_json CLOB NOT NULL,
    proposal_json CLOB,
    proposal_config_version BIGINT,
    approval_result_json CLOB,
    failure_reason VARCHAR(1000),
    created_at_ms BIGINT NOT NULL,
    updated_at_ms BIGINT NOT NULL,
    CONSTRAINT fk_task_case FOREIGN KEY (case_id) REFERENCES lab_cases(id)
);

CREATE TABLE IF NOT EXISTS lab_evidence (
    id VARCHAR(36) PRIMARY KEY,
    task_id VARCHAR(36) NOT NULL,
    tool VARCHAR(40) NOT NULL,
    data_json CLOB NOT NULL,
    config_version BIGINT NOT NULL,
    created_at_ms BIGINT NOT NULL,
    CONSTRAINT fk_evidence_task FOREIGN KEY (task_id) REFERENCES lab_tasks(id)
);

CREATE INDEX IF NOT EXISTS idx_evidence_task ON lab_evidence(task_id, created_at_ms);

CREATE TABLE IF NOT EXISTS lab_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id VARCHAR(36),
    case_id VARCHAR(100),
    event VARCHAR(60) NOT NULL,
    payload_json CLOB NOT NULL,
    created_at_ms BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_audit_task ON lab_audit(task_id, id);
CREATE INDEX IF NOT EXISTS idx_audit_case ON lab_audit(case_id, id);

CREATE TABLE IF NOT EXISTS lab_approvals (
    idempotency_key VARCHAR(200) PRIMARY KEY,
    task_id VARCHAR(36) NOT NULL UNIQUE,
    result_json CLOB NOT NULL,
    created_at_ms BIGINT NOT NULL,
    CONSTRAINT fk_approval_task FOREIGN KEY (task_id) REFERENCES lab_tasks(id)
);
